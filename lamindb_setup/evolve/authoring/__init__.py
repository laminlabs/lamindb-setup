"""What a plan file is written with.

The plan object and its context, the declarative surface, dtypes, and the
building blocks (features, records, schemas) a plan declares.  This layer
describes desired state; it does not know how to reach an instance.

Everything lives in private modules and is re-exported here, which is the only
way in.  Most of it is plan-author vocabulary, which the top-level package
re-exports from here in turn; the rest (`canonical_dtype_str`,
`parse_dtype`, ...) is what the engine needs to compare a plan with an
instance.
"""

