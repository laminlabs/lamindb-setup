"""Reaching an instance: turning desired state into applied state.

The apply pipeline, the lock file, the drift taxonomy, run tracking, plan
loading, teardown, and the ready-made data migrations that run against live
data.

Everything lives in private modules; the names the other layers need are
re-exported here, and this is the only way in.  The ready-made migrations are
plan-author vocabulary as well, so the top-level package re-exports them from
here in turn.

Patch a name on this module, not on the private module that defines it: a
re-export binds the value once, so a caller that imported it from here does not
see a later patch applied to its defining module.

The engine sits below the entry points and knows nothing of a command line: it
reports a failure by raising a :class:`~lamindb_setup.evolve.core.LaminSchemasError`
(an :class:`~lamindb_setup.evolve.core.InvalidArgumentError` for a bad plan
target), takes any prompt as a parameter, and prints through
:mod:`~lamindb_setup.evolve.console`.  Exit codes and prompts are the CLI's.
"""

